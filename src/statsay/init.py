"""`statsay init`: look at a project and write a starter statsay.yaml.

Two kinds of project are recognized:

- RPG Maker MV/MZ: a `data/` (or `www/data/`) folder with System.json and
  Items.json. Descriptions are read from the database; effect values and
  equipment parameters become fields; the game's own terms from System.json
  (HP/MP abbreviations, parameter names) become anchors.
- Generic: JSON arrays of objects with an `id`, plus CSV files with a key
  column and locale columns (and PO files named after a locale). Key patterns
  are guessed from keys that contain entity ids.

In both cases anchors are also mined from the data: a word next to a number in
a description that equals a field's value counts toward that field. Each word
goes to the one field it is most associated with, so words shared by many
fields ("restores", 「回復」) are dropped.
"""

from __future__ import annotations

import csv
import io
import json
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from statsay import StatsayError
from statsay.config import build_config
from statsay.extract import CONTROL_CODES, LABEL_SEPARATOR_RE, NUMBER_RE, _clause_starts, mask, normalize

SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", "dist", "build", ".pytest_cache"}
LOCALE_RE = re.compile(r"^[a-z]{2,3}(?:[_-][A-Za-z]{2,4})?$")
KEY_COLUMNS = ("key", "id", "keys", "string_id", "msgid")
# Runs of one script: latin words, percent, katakana/kanji, hiragana (particles, skipped as anchors).
RUN_RE = re.compile(r"[A-Za-z]+(?:['-][A-Za-z]+)*|%|[゠-ヿ一-鿿々ー]+|[぀-ゟ]+")
HIRAGANA_RE = re.compile(r"^[぀-ゟ]+$")
MAX_GAP = 20      # characters between a number and a mined anchor
MIN_COUNT = 2     # a mined anchor must sit next to a matching value at least this often
MIN_SHARE = 0.9   # ...and next to that field's values in this share of all its number-adjacent uses
MAX_ANCHORS = 4
# Function words are never anchors; the nearest word past them is used instead.
STOPWORDS = {"a", "an", "the", "to", "for", "by", "of", "and", "or", "with", "per", "at", "in", "on", "up",
             "is", "are", "be", "it", "its", "this", "that", "from", "into", "as", "your", "you", "all", "one"}

RPG_SOURCES = (("items", "Items.json", "item"), ("skills", "Skills.json", "skill"),
               ("weapons", "Weapons.json", "weapon"), ("armors", "Armors.json", "armor"))
EFFECT_FIELDS = {  # applies to items and skills
    "heal": ("effects[code=11].value2", {}), "heal_rate": ("effects[code=11].value1", {"scale": 100}),
    "mp": ("effects[code=12].value2", {}), "mp_rate": ("effects[code=12].value1", {"scale": 100}),
    "tp": ("effects[code=13].value1", {}), "grow": ("effects[code=42].value1", {}),
    "add_state": ("effects[code=21].dataId", {}), "cures": ("effects[code=22].dataId", {}),
}
STATE_FIELDS = ("add_state", "cures")
PERCENT_FIELDS = ("heal_rate", "mp_rate")
PARAMS = ("mhp", "mmp", "atk", "def", "mat", "mdf", "agi", "luk")
SCOPE_TERMS = {
    "ja": {1: ["敵単体", "敵1体"], 2: ["敵全体"], 7: ["味方単体", "味方1体", "味方1人"], 8: ["味方全体"], 11: ["使用者"]},
    "en": {1: ["one enemy", "a single enemy"], 2: ["all enemies"], 7: ["one ally", "a single ally"],
           8: ["all allies"], 11: ["the user"]},
}
# Comparisons and conditions name a value without claiming it ("more than cotton", "while poisoned").
CONTRAST_CUES = {
    "en": {"before": ["than", "instead of", "rather than", "in lieu of", "unlike", "while", "when", "if",
                      "during", "unless"]},
    "ja": {"after": ["より", "ではなく", "の代わりに", "の時", "の間", "時は", "中は"]},
}
# RPG Maker scope codes that target the same side and count as a plain scope term:
# 3 (one random enemy) is "one enemy"; 9/12 (one ally, dead / either) are "one ally";
# 10/13 (all allies, dead / either) are "all allies".
SCOPE_ALIASES = {1: [3], 7: [9, 12], 8: [10, 13]}


@dataclass
class Plan:
    """What init found; becomes statsay.yaml and the report."""
    kind: str
    raw: dict
    locales: list[str]
    notes: list[str] = field(default_factory=list)
    anchors: dict[str, list[str]] = field(default_factory=dict)  # field -> anchors (all locales), for the report


def init(root: Path) -> Plan:
    root = Path(root)
    if not root.is_dir():
        raise StatsayError(f"not a directory: {root}")
    data_dir = next((d for d in (root / "data", root / "www" / "data") if _is_rpgmaker(d)), None)
    plan = _rpgmaker(root, data_dir) if data_dir else _generic(root)
    _finish(root, plan)
    return plan


def render(plan: Plan) -> str:
    header = (
        "# Statsay configuration, generated by `statsay init`.\n"
        f"# Project kind: {plan.kind}. Review the anchors and vocabularies: they were guessed\n"
        "# from this project's data and descriptions. Term vocabularies only warn until you\n"
        "# mark them `validated: true`.\n\n"
    )
    return header + yaml.safe_dump(plan.raw, allow_unicode=True, sort_keys=False, width=110)


# --- RPG Maker -------------------------------------------------------------------------------------

def _rpgmaker(root: Path, data_dir: Path) -> Plan:
    system = _read_json(data_dir / "System.json") or {}
    rel = data_dir.relative_to(root).as_posix()
    sources, localization, bindings = [], [], []
    present = {}
    for source_id, file_name, kind in RPG_SOURCES:
        rows = _read_json(data_dir / file_name)
        if not isinstance(rows, list):
            continue
        described = [r for r in rows if isinstance(r, dict) and r.get("name") and str(r.get("description", "")).strip()]
        if not described:
            continue
        present[source_id] = described
        sources.append({"id": source_id, "path": f"{rel}/{file_name}", "format": "rpgmaker"})
    if not sources:
        raise StatsayError(f"{data_dir}: no items, skills, weapons or armors have descriptions")

    texts = [str(r["description"]) for rows in present.values() for r in rows]
    locale = _rpgmaker_locale(system, texts)
    for source in sources:
        kind = next(k for s, _, k in RPG_SOURCES if s == source["id"])
        localization.append({"format": "data", "source": source["id"], "field": "description",
                             "key": f"{kind}.{{id}}.description", "locale": locale})

    effect_sources = [s for s in ("items", "skills") if s in present]
    equip_sources = [s for s in ("weapons", "armors") if s in present]
    fields = {}
    for name, (path, options) in EFFECT_FIELDS.items():
        if effect_sources:
            fields[name] = {"source": effect_sources if len(effect_sources) > 1 else effect_sources[0],
                            "path": path, **options}
    for index, name in enumerate(PARAMS):
        if equip_sources:
            fields[name] = {"source": equip_sources if len(equip_sources) > 1 else equip_sources[0],
                            "path": f"params.{index}"}

    watched = {
        "items": [*EFFECT_FIELDS, "scope"], "skills": [*EFFECT_FIELDS, "mpCost", "tpCost", "scope"],
        "weapons": list(PARAMS), "armors": list(PARAMS),
    }
    for source in sources:
        kind = next(k for s, _, k in RPG_SOURCES if s == source["id"])
        bindings.append({"convention": f"{kind}.{{id}}.description", "source": source["id"],
                         "watched_fields": watched[source["id"]]})

    terms = system.get("terms") or {}
    basic = terms.get("basic") or []
    params = terms.get("params") or []
    term = lambda values, i: [values[i]] if len(values) > i and values[i] else []
    known = {
        "heal": term(basic, 3) + term(basic, 2), "mp": term(basic, 5) + term(basic, 4),
        "heal_rate": term(basic, 3) + term(basic, 2), "mp_rate": term(basic, 5) + term(basic, 4),
        # No seeds for mpCost/tpCost: a resource name next to a number is usually an amount
        # ("MPが2回復"), not a cost; cost anchors ("消費MP") are mined from the data instead.
        "tp": term(basic, 7) + term(basic, 6),
        "grow": [p for p in params[:8] if p],
        **{name: term(params, i) for i, name in enumerate(PARAMS)},
    }
    # Translations exported by a plugin: CSV files keyed like the database strings (item.{id}.description).
    locales = [locale]
    patterns = re.compile(r"^(item|skill|weapon|armor)\.\d+\.description$")
    for path in _walk(root):
        if path.suffix.lower() != ".csv":
            continue
        header = _csv_header(path)
        key = next((h for h in header if h.lower() in KEY_COLUMNS), None)
        extra = [h for h in header if h != key and LOCALE_RE.match(h) and h not in locales]
        if not key or not extra:
            continue
        rows = list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8-sig"), newline="")))
        if rows and sum(bool(patterns.match(r.get(key) or "")) for r in rows) >= 0.5 * len(rows):
            localization.append({"path": path.relative_to(root).as_posix(), "format": "csv", "key_column": key,
                                 "locales": extra, "control_codes": "rpgmaker"})
            locales.extend(extra)

    raw = {"data_sources": sources, "localization": localization, "fields": fields, "bindings": bindings,
           "claims": {}}
    plan = Plan(kind=f"RPG Maker {'MZ' if 'advanced' in system else 'MV'} ({rel}/)", raw=raw, locales=locales)
    plan.notes.append(f"locale {locale!r} from " + ("System.json" if system.get("locale") else "the descriptions"))
    if len(locales) > 1:
        plan.notes.append(f"translations found for: {', '.join(locales[1:])}")
    plan.raw["_known_anchors"] = {locale: known}
    plan.raw["_states"] = {str(s["id"]): s["name"] for s in (_read_json(data_dir / "States.json") or [])
                           if isinstance(s, dict) and s.get("name") and not s["name"].startswith("-")}
    return plan


def _is_rpgmaker(data_dir: Path) -> bool:
    """An RPG Maker database: Items.json is an array that starts with null (entry 0 is unused)."""
    items = _read_json(data_dir / "Items.json") if (data_dir / "Items.json").is_file() else None
    return isinstance(items, list) and bool(items) and items[0] is None


def _rpgmaker_locale(system: dict, texts: list[str]) -> str:
    code = str(system.get("locale") or "")
    if code:
        return code.split("_")[0].split("-")[0].lower()
    kana = sum(1 for t in texts if re.search(r"[぀-ヿ]", t))
    return "ja" if kana > len(texts) / 2 else "en"


# --- Generic JSON + CSV/PO -------------------------------------------------------------------------

def _generic(root: Path) -> Plan:
    data, csvs, pos = {}, [], []
    for path in _walk(root):
        rel = path.relative_to(root).as_posix()
        if path.suffix.lower() == ".json":
            rows = _read_json(path)
            if (isinstance(rows, list) and len(rows) >= 2
                    and sum(isinstance(r, dict) and "id" in r for r in rows) >= 0.8 * len(rows)):
                data[rel] = [r for r in rows if isinstance(r, dict) and "id" in r]
        elif path.suffix.lower() == ".csv":
            header = _csv_header(path)
            key = next((h for h in header if h.lower() in KEY_COLUMNS), None)
            locales = [h for h in header if h != key and LOCALE_RE.match(h)]
            if key and locales:
                csvs.append((rel, key, locales))
        elif path.suffix.lower() == ".po" and LOCALE_RE.match(path.stem):
            pos.append((rel, path.stem))
    if not data or not csvs:
        raise StatsayError(f"{root}: found no RPG Maker database, and no JSON data (arrays of objects with an "
                           "'id') together with a CSV localization file (a key column plus locale columns)")

    keys: dict[str, str] = {}
    for rel, key_column, locales in csvs:
        for row in csv.DictReader(io.StringIO((root / rel).read_text(encoding="utf-8-sig"), newline="")):
            k = (row.get(key_column) or "").strip()
            if k:
                keys[k] = " ".join(row.get(locale) or "" for locale in locales)

    sources, bindings, notes = [], [], []
    used_ids = set()
    for rel, rows in sorted(data.items()):
        source_id = _unique(re.sub(r"\W+", "_", Path(rel).stem).strip("_").lower() or "data", used_ids)
        ids = {str(r["id"]) for r in rows}
        templates: dict[str, set] = defaultdict(set)
        for k in keys:
            parts = re.split(r"([._:/-])", k)
            for i, part in enumerate(parts):
                if part in ids:
                    templates["".join(parts[:i] + ["{id}"] + parts[i + 1:])].add(part)
        candidates = [t for t, hit in templates.items() if len(hit) >= max(2, 0.3 * len(ids))]
        if not candidates:
            continue
        # Prefer the key pattern whose strings state the most numbers: usually descriptions, not names.
        best = max(candidates, key=lambda t: (sum(bool(re.search(r"\d", keys.get(t.replace("{id}", i), "")))
                                                  for i in ids), len(templates[t])))
        numeric = sorted({k for r in rows for k, v in r.items()
                          if isinstance(v, (int, float)) and not isinstance(v, bool) and k != "id"})
        if not numeric:
            notes.append(f"{rel}: no numeric fields to watch")
            continue
        sources.append({"id": source_id, "path": rel})
        bindings.append({"convention": best, "source": source_id, "watched_fields": numeric})
    if not sources:
        raise StatsayError(f"{root}: no CSV keys contain the ids of the JSON data, so no key pattern was found")

    localization = [{"path": rel, "format": "csv", "key_column": key, "locales": locales}
                    for rel, key, locales in csvs]
    all_locales = [locale for _, _, locales in csvs for locale in locales]
    source_locale = "en" if "en" in all_locales else all_locales[0]
    for rel, locale in pos:
        if locale not in all_locales:
            localization.append({"path": rel, "format": "po", "locale": locale, "source_locale": source_locale})
            all_locales.append(locale)
    raw = {"data_sources": sources, "localization": localization, "bindings": bindings, "claims": {}}
    return Plan(kind="JSON data with CSV/PO localization", raw=raw, locales=all_locales, notes=notes)


# --- Shared: load, mine anchors, vocabularies --------------------------------------------------------

def _finish(root: Path, plan: Plan) -> None:
    from statsay.binding import resolve
    from statsay.engine import _load

    raw = plan.raw
    known = raw.pop("_known_anchors", {})
    states = raw.pop("_states", {})
    # Load once with every candidate field watched, then keep what the data actually has.
    numeric_names = {n for b in raw["bindings"] for n in b["watched_fields"]} - {"scope", *STATE_FIELDS}
    raw["claims"] = {n: {"kind": "number"} for n in numeric_names}
    config = build_config(raw, root)
    entities, strings = _load(config)
    bindings, coverage, _ = resolve(config, entities, strings)

    has_value = defaultdict(set)   # source -> fields with a non-zero numeric value somewhere
    has_any = defaultdict(set)     # source -> fields present at all (incl. enums)
    for b in bindings:
        for name in b.watched_fields:
            value = b.entity.fields.get(name)
            if value is not None:
                has_any[b.entity.source].add(name)
            if isinstance(value, (int, float)) and not isinstance(value, bool) and value:
                has_value[b.entity.source].add(name)

    mined, mentions = _mine(bindings, strings, plan.locales, has_value)
    claims: dict[str, dict] = {}
    for b in raw["bindings"]:
        source = b["source"]
        # Watch a numeric field if some description states its value, or if it is an RPG Maker
        # effect (what the item or skill does), which descriptions describe even without numbers.
        keep = [n for n in b["watched_fields"]
                if (n in has_value[source] and (mentions[(source, n)] or n in EFFECT_FIELDS))
                or (n in ("scope", *STATE_FIELDS) and n in has_any[source])]
        dropped = [n for n in b["watched_fields"] if n in has_value[source] and n not in keep]
        if dropped:
            plan.notes.append(f"{source}: not watching {', '.join(dropped)} (no description states their values)")
        b["watched_fields"] = keep
        for name in keep:
            if name in numeric_names and name not in claims:
                anchors = {}
                for locale in plan.locales:
                    terms = _dedupe(mined.get((locale, name), []) + known.get(locale, {}).get(name, []))
                    if terms:
                        anchors[locale] = terms
                plan.anchors[name] = [t for terms in anchors.values() for t in terms]
                if anchors:  # without anchors, any lone number would be tied to it: watch it, don't claim it
                    claims[name] = {"kind": "number", **({"unit": "percent"} if name in PERCENT_FIELDS else {}),
                                    "anchors": anchors}

    texts = {locale: [loc.text for by_locale in strings.values() for l, loc in by_locale.items() if l == locale]
             for locale in plan.locales}
    if any("scope" in b["watched_fields"] for b in raw["bindings"]):
        vocabulary = {}
        for locale in plan.locales:
            for value, terms in SCOPE_TERMS.get(locale, {}).items():
                seen = [t for t in terms if any(t.casefold() in s.casefold() for s in texts[locale])]
                if seen:
                    entry = vocabulary.setdefault(value, {})
                    entry[locale] = seen
                    if value in SCOPE_ALIASES:
                        entry["aliases"] = SCOPE_ALIASES[value]
        if vocabulary:
            claims["scope"] = {"kind": "enum", "vocabulary": vocabulary}
    for name in STATE_FIELDS:
        if any(name in b["watched_fields"] for b in raw["bindings"]) and states:
            vocabulary = {}
            # Only states that some effect adds or removes: others are applied in ways the data
            # doesn't show (common events, plugins), so a mention of them can't be checked.
            used = {int(v) for b in bindings for f in STATE_FIELDS
                    for v in (b.entity.fields.get(f) if isinstance(b.entity.fields.get(f), list)
                              else [b.entity.fields.get(f)]) if isinstance(v, int) and v}
            by_name: dict[str, list[int]] = defaultdict(list)
            for state_id, state_name in states.items():
                if int(state_id) in used:
                    by_name[state_name].append(int(state_id))
            for state_name, ids in by_name.items():
                for locale in plan.locales:
                    if any(state_name in s for s in texts[locale]):
                        entry = vocabulary.setdefault(ids[0], {})
                        entry[locale] = [state_name]
                        if len(ids) > 1:
                            entry["aliases"] = ids[1:]
            if vocabulary:
                claims[name] = {"kind": "enum", "vocabulary": vocabulary}
    for b in raw["bindings"]:  # enums without any vocabulary term in the text are dropped
        b["watched_fields"] = [n for n in b["watched_fields"] if n in claims or n in numeric_names]
    raw["bindings"] = [b for b in raw["bindings"] if b["watched_fields"]]
    if "fields" in raw:
        used = {n for b in raw["bindings"] for n in b["watched_fields"]}
        raw["fields"] = {n: f for n, f in raw["fields"].items() if n in used}
        if not raw["fields"]:
            del raw["fields"]
    raw["claims"] = claims
    cues = {locale: CONTRAST_CUES[locale] for locale in plan.locales if locale in CONTRAST_CUES}
    if cues and any(c["kind"] == "enum" for c in claims.values()):
        raw["contrast_cues"] = cues
    for c in coverage:
        plan.notes.append(f"{c.rule}: {c.bound} of {c.entities} {c.source} have a string")


def _mine(bindings, strings, locales, has_value) -> tuple[dict[tuple[str, str], list[str]], Counter]:
    """Anchors per (locale, field), learned from words next to numbers that equal the field's value.

    Also returns how often each (source, field)'s value is stated in a description.
    """
    mentions: Counter = Counter()
    near_field: dict[tuple[str, str, str], Counter] = defaultdict(Counter)  # (locale, source, run) -> field counts
    near_any: Counter = Counter()                                           # (locale, source, run) -> all
    shown: dict[tuple[str, str], Counter] = defaultdict(Counter)            # (locale, run lower) -> spellings
    for b in bindings:
        source = b.entity.source
        values = {name: abs(v) for name, v in b.entity.fields.items()
                  if name in has_value[source] and isinstance(v, (int, float)) and not isinstance(v, bool) and v}
        for locale, loc in strings[b.key].items():
            if locale not in locales:
                continue
            norm, _ = normalize(mask(loc.text, CONTROL_CODES.get(loc.codes)))
            starts = _clause_starts(norm)
            clause = lambda pos: sum(1 for s in starts if s <= pos)
            runs = [(m.start(), m.end(), m.group()) for m in RUN_RE.finditer(norm)
                    if not HIRAGANA_RE.match(m.group()) and m.group().casefold() not in STOPWORDS]
            for number in NUMBER_RE.finditer(norm):
                value = float(number.group().replace(",", ""))
                before = [r for r in runs if r[1] <= number.start() and number.start() - r[1] <= MAX_GAP
                          and clause(r[0]) == clause(number.start())][-1:]
                after = [r for r in runs if r[0] >= number.end() and r[0] - number.end() <= MAX_GAP
                         and clause(r[0]) == clause(number.start())][:1]
                if before and LABEL_SEPARATOR_RE.match(norm[before[0][1]:number.start()]):
                    after = []
                elif after and re.match(r"^\s*[+\-:：=＋−]\s*\d", norm[after[0][1]:]):
                    after = []  # the word after labels the next number ("5 WIS+5")
                matches = [name for name, v in values.items() if abs(v - value) < 1e-9]
                for name in matches:
                    mentions[(source, name)] += 1
                for _, _, text in before + after:
                    key = (locale, source, text.casefold())
                    shown[(locale, text.casefold())][text] += 1
                    if len(matches) > 1:
                        continue  # equal to several fields ("STR+5 LUK+5"): no evidence either way
                    near_any[key] += 1
                    for name in matches:
                        near_field[key][name] += 1
    out: dict[tuple[str, str], list[tuple[int, str]]] = defaultdict(list)
    for (locale, source, run), counts in near_field.items():
        name, count = counts.most_common(1)[0]
        if count >= MIN_COUNT and count / near_any[(locale, source, run)] >= MIN_SHARE:
            out[(locale, name)].append((count, shown[(locale, run)].most_common(1)[0][0]))
    anchors = {key: _dedupe([t for _, t in sorted(found, reverse=True)])[:MAX_ANCHORS] for key, found in out.items()}
    return anchors, mentions


def _walk(root: Path):
    for path in sorted(root.rglob("*")):
        if path.is_file() and not any(part in SKIP_DIRS for part in path.relative_to(root).parts) \
                and len(path.relative_to(root).parts) <= 5:
            yield path


def _read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"), strict=False)
    except (OSError, ValueError):
        return None


def _csv_header(path: Path) -> list[str]:
    try:
        with path.open(encoding="utf-8-sig", newline="") as handle:
            return next(csv.reader(handle), [])
    except (OSError, UnicodeDecodeError):
        return []


def _dedupe(values):
    seen, out = set(), []
    for value in values:
        if value.casefold() not in seen:
            seen.add(value.casefold())
            out.append(value)
    return out


def _unique(name, used):
    candidate, n = name, 2
    while candidate in used:
        candidate, n = f"{name}_{n}", n + 1
    used.add(candidate)
    return candidate
